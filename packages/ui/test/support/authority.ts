/**
 * The shared test helper for UI tests against a real in-process authority
 * (vtt-3l6.21; M4-D13, M4-D18). It starts `startServer` on port 0 over an
 * in-memory host or a temp-file host, and creates table sessions and
 * protocol clients that use the `ws` client: jsdom's WebSocket cannot open a
 * connection under Vitest, so every socket here is a Node one, also in jsdom
 * tests. Call `cleanupAuthorities()` in `afterEach`.
 */
import { mkdtemp, realpath, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  type AutosaveOptions,
  type CompactionPolicy,
  type DiceSource,
  DocumentStore,
  type HttpHandler,
  newTableSnapshot,
  type RunningServer,
  startServer,
  TableHost,
} from "@vtt/authority";
import { ProtocolClient, type WebSocketConstructor, type WebSocketLike } from "@vtt/protocol";
import type { Snapshot } from "@vtt/schema";
import { createTableSession, type TableSession } from "@vtt/ui";
import { WebSocket as NodeWs } from "ws";

/** jsdom's default origin, accepted by default. */
export const JSDOM_ORIGIN = "http://localhost:3000";

/** Called with every frame a socket sends; return false to swallow it (never written). */
export type SendHook = (data: string) => boolean | undefined;

/** A `WebSocketConstructor` over the `ws` client, optionally observing sends. */
export function nodeWebSocket(onSend?: SendHook): WebSocketConstructor {
  return class NodeSocket implements WebSocketLike {
    readonly #ws: NodeWs;
    constructor(url: string) {
      this.#ws = new NodeWs(url);
      // An error before the open is followed by a close, which the client handles.
      this.#ws.on("error", () => undefined);
    }
    send(data: string): void {
      if (onSend?.(data) === false) return;
      this.#ws.send(data);
    }
    close(code?: number, reason?: string): void {
      this.#ws.close(code, reason);
    }
    // biome-ignore lint/suspicious/noExplicitAny: matches WebSocketLike
    addEventListener(type: string, listener: (event: any) => void): void {
      this.#ws.addEventListener(type as "message", listener);
    }
  };
}

/** The plain `ws` client constructor. */
export const NodeWebSocket: WebSocketConstructor = nodeWebSocket();

export interface AuthorityOptions {
  /** Back the host with a new temp file (autosave off), so `save` writes it. Default: in memory. */
  file?: boolean;
  /** The in-memory host's initial document (default: a new table with the GM board). */
  snapshot?: Snapshot;
  /** Origins accepted besides the server's own (default: jsdom's origin). */
  allowOrigins?: readonly string[];
  /** The host's dice source, e.g. a `ScriptedDiceSource` (default: the host's random dice). */
  dice?: DiceSource;
  /**
   * HTTP route handlers (`startServer`'s `http`), or a function building them
   * from the host (e.g. `(host) => [createAssetHttpHandler({ host })]`),
   * called once before the first server starts.
   */
  http?: readonly HttpHandler[] | ((host: TableHost) => readonly HttpHandler[]);
  /** Default: generated by the server. */
  token?: string;
  /** The file-backed host's save-time compaction (M6-D33); implies `file`. Default `"never"`. */
  compaction?: CompactionPolicy;
  /** The file-backed host's autosave timings (default off). */
  autosave?: Partial<AutosaveOptions>;
}

export interface ClientOptions {
  /** `agent` connections act as `{type: "agent", name}`; `ui` and `test` as the GM. Default `test`. */
  kind?: "ui" | "agent" | "test";
}

export interface SessionOptions {
  /** Default: `NodeWebSocket`. */
  WebSocket?: WebSocketConstructor;
}

export interface TestAuthority {
  /** The current server's WebSocket URL (unchanged by `restart`: same port). */
  readonly url: string;
  /** The current server's token. */
  readonly token: string;
  readonly host: TableHost;
  /** The current server. */
  readonly server: RunningServer;
  /** The table file of a file-backed host, else null. */
  readonly path: string | null;
  /** A connected protocol client named `name`, closed by the cleanup. */
  client(name: string, options?: ClientOptions): Promise<ProtocolClient>;
  /** A table session on this authority (with the `ws` client), closed by the cleanup. */
  session(options?: SessionOptions): TableSession;
  /** Stops the server and starts another on its port over the same host: a new `session`. */
  restart(options?: { token?: string }): Promise<RunningServer>;
  /** Closes sessions, clients, the server and the host, and removes the temp directory. */
  cleanup(): Promise<void>;
}

const started = new Set<TestAuthority>();

/** Starts an in-process authority on port 0. */
export async function startAuthority(options: AuthorityOptions = {}): Promise<TestAuthority> {
  let dir: string | null = null;
  let path: string | null = null;
  let host: TableHost;
  const dice = options.dice === undefined ? {} : { dice: options.dice };
  if (options.file || options.compaction !== undefined) {
    dir = await realpath(await mkdtemp(join(tmpdir(), "vtt-ui-")));
    path = join(dir, "table.json");
    host = await TableHost.open(path, {
      createIfMissing: true,
      autosave: options.autosave ?? false,
      ...dice,
      ...(options.compaction === undefined ? {} : { compaction: options.compaction }),
    });
  } else {
    host = TableHost.inMemory(
      DocumentStore.fromSnapshot(options.snapshot ?? newTableSnapshot()),
      dice,
    );
  }
  const allowOrigins = options.allowOrigins ?? [JSDOM_ORIGIN];
  const http = typeof options.http === "function" ? options.http(host) : options.http;
  const serve = (port: number, token: string | undefined) =>
    startServer({
      host,
      port,
      allowOrigins,
      ...(http === undefined ? {} : { http }),
      ...(token === undefined ? {} : { token }),
    });

  let server = await serve(0, options.token);
  const sessions: TableSession[] = [];
  const clients: ProtocolClient[] = [];
  let closed = false;

  const authority: TestAuthority = {
    get url() {
      return server.url;
    },
    get token() {
      return server.token;
    },
    host,
    get server() {
      return server;
    },
    path,
    async client(name, clientOptions = {}) {
      const client = new ProtocolClient({
        url: server.url,
        token: server.token,
        client: { name, kind: clientOptions.kind ?? "test" },
        WebSocket: NodeWebSocket,
        onWarning: () => undefined,
      });
      clients.push(client);
      await client.connect();
      return client;
    },
    session(sessionOptions = {}) {
      const session = createTableSession({
        url: server.url,
        token: server.token,
        WebSocket: sessionOptions.WebSocket ?? NodeWebSocket,
      });
      sessions.push(session);
      return session;
    },
    async restart(restartOptions = {}) {
      const port = server.port;
      const token = restartOptions.token ?? server.token;
      await server.close("restart");
      server = await serve(port, token);
      return server;
    },
    async cleanup() {
      if (closed) return;
      closed = true;
      started.delete(authority);
      for (const s of sessions.splice(0)) s.close();
      for (const c of clients.splice(0)) c.close();
      await server.close();
      await host.close().catch(() => undefined);
      if (dir !== null) await rm(dir, { recursive: true, force: true });
    },
  };
  started.add(authority);
  return authority;
}

/** Cleans up every authority started and not yet cleaned up (for `afterEach`). */
export async function cleanupAuthorities(): Promise<void> {
  await Promise.all([...started].map((a) => a.cleanup()));
}

/**
 * Waits for `pred`, polling every 5 ms, or fails after `ms`. The default is
 * generous because a round trip through the in-process authority can take
 * seconds on a loaded CI runner (vtt-qf5.9); a passing wait returns at once.
 */
export async function until(pred: () => boolean, what: string, ms = 20_000): Promise<void> {
  const end = Date.now() + ms;
  while (!pred()) {
    if (Date.now() > end) throw new Error(`timed out waiting for ${what}`);
    await new Promise((r) => setTimeout(r, 5));
  }
}

/** Waits until `session` is ready. */
export function whenReady(session: TableSession, ms = 4000): Promise<void> {
  return until(() => session.getSnapshot().ready, "the session to be ready", ms);
}
